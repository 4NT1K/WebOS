//! Putting GRUB on the disk, and telling it how to find the system.
//!
//! There is exactly one bootloader. GRUB is the only one that installs
//! cleanly onto both a UEFI ESP and a BIOS MBR from the same medium, which
//! matters because the live image boots both ways and we do not get to know
//! how the user booted until after the fact.
//!
//! The kernel command line is the interesting part. It has to name the root
//! device (by UUID, because `/dev/sda3` means nothing on the next boot), open
//! the LUKS container first if there is one, and select the btrfs subvolume —
//! without `rootflags=subvol=@` a btrfs root mounts subvolid 5 and finds no
//! `/sbin/init`.

use std::path::Path;

use anyhow::{bail, Result};

use crate::config::{Encryption, Filesystem, Firmware, InstallConfig};
use crate::disk;
use crate::exec::Runner;
use crate::install::{in_chroot, Partitions, CRYPT_NAME, TARGET};

/// Install GRUB into the target and generate its configuration.
pub fn install(r: &Runner, cfg: &InstallConfig, p: &Partitions) -> Result<()> {
    r.phase("Installing the bootloader");

    if !cfg.use_grub {
        bail!(
            "only GRUB is supported by the installer; \
             install another bootloader by hand if you must"
        );
    }
    if cfg.disk.is_empty() {
        bail!("no target disk");
    }

    let root_uuid = uuid_of(r, &p.root_raw);
    if root_uuid.is_empty() {
        bail!("could not read the UUID of {}", p.root_raw);
    }

    let cmdline = kernel_cmdline(cfg, &root_uuid);
    r.info(format!("cmdline: {cmdline}"));

    write_grub_default(r, cfg, &cmdline)?;
    in_chroot(r, &grub_script(cfg, p))?;

    r.info("bootloader installed");
    Ok(())
}

/// The one line that decides whether the machine comes back up.
pub fn kernel_cmdline(cfg: &InstallConfig, root_uuid: &str) -> String {
    let mut parts: Vec<String> = vec![
        "quiet".into(),
        "loglevel=3".into(),
        // Watchdog timers cost power and buy a desktop nothing.
        "nowatchdog".into(),
    ];

    match cfg.encryption {
        Encryption::Luks => {
            // rd.luks.name=<uuid>=<name> opens the container in the initramfs
            // and creates /dev/mapper/<name>; root then points at the mapper.
            parts.push(format!("rd.luks.name={root_uuid}={CRYPT_NAME}"));
            parts.push(format!("root=/dev/mapper/{CRYPT_NAME}"));
        }
        Encryption::None => parts.push(format!("root=UUID={root_uuid}")),
    }

    if cfg.filesystem == Filesystem::Btrfs {
        parts.push("rootflags=subvol=@".into());
    }

    // NVIDIA's proprietary driver only modesets if it is asked to at boot.
    if cfg.nvidia {
        parts.push("nvidia-drm.modeset=1".into());
        parts.push("nvidia.NVreg_PreserveVideoMemoryAllocations=1".into());
    }

    parts.join(" ")
}

fn write_grub_default(r: &Runner, cfg: &InstallConfig, cmdline: &str) -> Result<()> {
    let mut s = String::from(
        "# /etc/default/grub — generated by the WebOS installer.\n\
         # Edit it, then run: grub-mkconfig -o /boot/grub/grub.cfg\n\n",
    );
    s.push_str("GRUB_DISTRIBUTOR=\"SanusOS\"\n");
    s.push_str("GRUB_DEFAULT=0\n");
    s.push_str("GRUB_TIMEOUT=3\n");
    s.push_str("GRUB_TIMEOUT_STYLE=menu\n");
    s.push_str("GRUB_GFXMODE=auto\n");
    s.push_str("GRUB_GFXPAYLOAD_LINUX=keep\n");
    s.push_str("GRUB_DISABLE_RECOVERY=true\n");
    s.push_str("GRUB_DISABLE_SUBMENU=y\n");
    // Other operating systems on the disk are the user's, not ours.
    s.push_str("GRUB_DISABLE_OS_PROBER=false\n\n");
    s.push_str(&format!("GRUB_CMDLINE_LINUX_DEFAULT=\"{cmdline}\"\n"));
    s.push_str("GRUB_CMDLINE_LINUX=\"\"\n");

    if cfg.encryption == Encryption::Luks {
        // /boot itself is not encrypted; the initramfs opens the container.
        s.push_str("\n# root is LUKS2; the container is opened by the initramfs.\n");
    }

    r.write_target(Path::new(TARGET), "/etc/default/grub", &s)
}

fn grub_script(cfg: &InstallConfig, p: &Partitions) -> String {
    let _ = p;
    let mut s = String::new();
    s.push_str("#!/bin/bash\n");
    s.push_str("set -euo pipefail\n");
    s.push_str("export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin\n\n");
    s.push_str("mkdir -p /boot/grub\n\n");

    match cfg.firmware {
        Firmware::Uefi => {
            s.push_str("echo 'installing GRUB for x86_64-efi'\n");
            s.push_str("mkdir -p /boot/efi\n");
            // If we were booted in BIOS mode the firmware's variables are not
            // writable; skip the NVRAM entry rather than failing the install.
            let nvram = if disk::is_efi() { "" } else { " --no-nvram" };
            s.push_str(&format!(
                "grub-install --target=x86_64-efi \\\n\
                 \t--efi-directory=/boot/efi \\\n\
                 \t--bootloader-id=WebOS \\\n\
                 \t--recheck{nvram}\n\n"
            ));
            // A fallback copy under the removable-media path, so the machine
            // still boots if the NVRAM entry is lost (a firmware update, a
            // CMOS reset, a second disk).
            s.push_str("if [[ -f /boot/efi/EFI/WebOS/grubx64.efi ]]; then\n");
            s.push_str("  mkdir -p /boot/efi/EFI/BOOT\n");
            s.push_str("  cp -f /boot/efi/EFI/WebOS/grubx64.efi /boot/efi/EFI/BOOT/BOOTX64.EFI\n");
            s.push_str("fi\n\n");
        }
        Firmware::Bios => {
            s.push_str("echo 'installing GRUB for i386-pc'\n");
            s.push_str(&format!(
                "grub-install --target=i386-pc --recheck --boot-directory=/boot {}\n\n",
                cfg.disk
            ));
        }
    }

    s.push_str("grub-mkconfig -o /boot/grub/grub.cfg\n");
    s
}

fn uuid_of(r: &Runner, dev: &str) -> String {
    r.capture("blkid", &["-s", "UUID", "-o", "value", dev])
        .unwrap_or_default()
}
